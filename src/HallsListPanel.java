    private void addHall(String name, boolean available) {
    JPanel row = new JPanel(new BorderLayout());                        // صف واحد للقاعة
    row.setBorder(BorderFactory.createEmptyBorder(5, 10, 5, 10));       // مسافات حول الصف
    row.setMaximumSize(new Dimension(Integer.MAX_VALUE, 50));           // ارتفاع الصف

    JLabel nameLabel = new JLabel(name);                                // اسم القاعة
    JButton bookButton = new JButton(available ? "Book" : "Unavailable");
    bookButton.setEnabled(available);                                   // غير المتاحة يتعطل زرها

    row.add(nameLabel, BorderLayout.CENTER);                            // الاسم على اليسار
    row.add(bookButton, BorderLayout.EAST);                             // الزر على اليمين
    hallsPanel.add(row);                                                // نضيف الصف للقائمة
}
